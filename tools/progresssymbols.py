"""Decode /Game/Modes/DT_ProgressSymbol (latest pak wins) and print its rows; with --main, write the MainProgress story
line that CoopProgress reads (mods/CoopProgress/main_progress.txt). Read-only.
Usage: python -I progresssymbols.py <paks dir> [--main <out.txt>]
UE 4.18 DataTable: object tagged properties up to None, int32 GUID flag, int32 row count, then per row an FName and the
row struct's tagged properties up to None. Rows of type MainProgress, in file order, make the story line."""
import os, struct, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pakv4
sys.stdout.reconfigure(encoding='utf-8')   # some symbols hold full-width characters

paks = sys.argv[1]
order = sorted([f for f in os.listdir(paks) if f.endswith('.pak')], key=lambda f: (f.replace('_0_P', '').replace('_0_p', ''), '_0_p' in f.lower()))
src = {}
for f in order:
    p = pakv4.Pak(os.path.join(paks, f))
    for n in p.entries:
        for ext in ('.uasset', '.uexp'):
            if n.endswith('/Modes/DT_ProgressSymbol' + ext): src[ext] = (p, n)
ua = src['.uasset'][0].read(src['.uasset'][1])
o = 8 + 4 + 4 + 4
nc, = struct.unpack_from('<i', ua, o); o += 4 + nc * 20 + 4
_, o = pakv4._fstr(ua, o); o += 4                       # folder name, package flags
count, q = struct.unpack_from('<ii', ua, o)
names = []
for _ in range(count):
    s, q = pakv4._fstr(ua, q); q += 4; names.append(s)
b = src['.uexp'][0].read(src['.uexp'][1])

def fname(o):
    i, n = struct.unpack_from('<ii', b, o)
    return names[i] + ('_%d' % (n - 1) if n else ''), o + 8

def props(o, strings):
    dtype = None
    while True:
        pname, o = fname(o)
        if pname == 'None': return o, dtype
        ptype, o = fname(o)
        size, = struct.unpack_from('<i', b, o); o += 8      # size, array index
        inner = None
        if ptype == 'StructProperty': _, o = fname(o); o += 16
        elif ptype == 'BoolProperty': o += 1
        elif ptype in ('ByteProperty', 'EnumProperty'): _, o = fname(o)
        elif ptype == 'ArrayProperty': inner, o = fname(o)
        elif ptype == 'MapProperty': o += 16
        o += 1 + (16 if b[o] else 0)                        # property GUID
        start = o
        if ptype == 'EnumProperty' and pname == 'DataType':
            dtype, _ = fname(o)
        elif ptype == 'ArrayProperty' and inner == 'StrProperty':
            n, = struct.unpack_from('<i', b, o); r = o + 4
            for _ in range(n):
                s, r = pakv4._fstr(b, r); strings.append(s)
        o = start + size

o, _ = props(0, [])
o += 4
rows, = struct.unpack_from('<i', b, o); o += 4
line = []
for i in range(rows):
    row, o = fname(o)
    strings = []
    o, dtype = props(o, strings)
    print('%d\t%s\t%s\t%s' % (i, row, dtype, ' | '.join(strings)))
    if dtype == 'EN_ProgressDataType::MainProgress':
        line += [(row, s) for s in strings if s]
if '--main' in sys.argv:
    out = sys.argv[sys.argv.index('--main') + 1]
    with open(out, 'w', encoding='utf-8', newline='\n') as w:
        w.write('# Code Vein main story line, in order: row<TAB>symbol. From DT_ProgressSymbol (MainProgress rows, file order).\n')
        w.write('# Generated by tools/progresssymbols.py from Steam build 1.53.93354.\n')
        for row, s in line: w.write(row + '\t' + s + '\n')
    print(len(line), 'symbols ->', out, file=sys.stderr)
